// Replay existing public deterministic journal through current production exports.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
const root=process.env.PRL_ROOT??process.cwd();
const output=process.env.PRL_REVIEW_OUTPUT??'/workspace/shared/prl-final-wallet-boundary-review';
const input=process.env.PRL_REVIEW_JOURNAL??path.join(output,'backup-ceiling-journal.json');
const hash=text=>createHash('sha256').update(text).digest('hex');
const w=await import(pathToFileURL(root+'/packages/wallet/src/index.ts'));
const s=await import(pathToFileURL(root+'/packages/sdk/src/index.ts'));
const original=fs.readFileSync(input,'utf8');
const backup=JSON.parse(original);
const a=s.accountFromJson(backup.account);
const before=structuredClone(backup.journal);
for(const p of backup.journal.payments)p.lastError='\u0000'.repeat(1000);
const exportStart=performance.now();
const exported=w.exportWalletBackup(a,backup.journal);
const exportMs=performance.now()-exportStart;
assert.deepEqual(JSON.parse(exported),{...backup,journal:before});
assert.equal(Buffer.byteLength(exported),16218359);
assert.equal(hash(exported),hash(original));
let timerFired=false,timerMs;
const start=performance.now();
const timer=new Promise(resolve=>setTimeout(()=>{timerFired=true;timerMs=performance.now()-start;resolve();},0));
const restored=w.importWalletBackup(exported);
const importMs=performance.now()-start;
const timerRanDuringImport=timerFired;
assert.deepEqual(restored.account,a);
const expected=structuredClone(before);
for(const p of expected.payments)delete p.archived;
assert.deepEqual(restored.journal,expected);
assert.equal(w.reservedOutpoints(restored.journal).size,32000);
await timer;
const result={records:2000,signatures:32000,bytes:Buffer.byteLength(exported),exportMs,importMs,timerMs,timerRanDuringImport,exportSha256:hash(exported),sourceSha256:Object.fromEntries(['packages/wallet/src/recovery.ts','packages/sdk/src/transaction.ts','packages/sdk/src/keys.ts','packages/sdk/src/bundle.ts'].map(p=>[p,hash(fs.readFileSync(path.join(root,p)))])),semantics:'All recovery fields exact; only local diagnostics omitted on export and imported archival authority discarded by unchanged validation'};
fs.writeFileSync(path.join(output,'parent-roundtrip.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
