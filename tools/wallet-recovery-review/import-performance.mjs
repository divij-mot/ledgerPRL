import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const root=process.env.PRL_ROOT??process.cwd();
const output=process.env.PRL_REVIEW_OUTPUT??'/workspace/shared/prl-final-wallet-boundary-review';
const w=await import(pathToFileURL(root+'/packages/wallet/src/index.ts'));
const text=fs.readFileSync(process.env.PRL_REVIEW_JOURNAL??path.join(output,'backup-ceiling-journal.json'),'utf8');
let fired=false,delay;
const start=performance.now();
const tick=new Promise(resolve=>setTimeout(()=>{fired=true;delay=performance.now()-start;resolve();},0));
const restored=w.importWalletBackup(text);
const elapsed=performance.now()-start;
assert.equal(restored.journal.payments.length,2000);
assert.equal(w.reservedOutpoints(restored.journal).size,32000);
assert.equal(restored.journal.nextChangeIndex,2000);
assert(restored.journal.payments.every(p=>p.rawTx&&p.txid&&!p.archived));
const timerRanDuringImport=fired;
await tick;
const result={records:2000,signatures:32000,bytes:Buffer.byteLength(text),importMs:elapsed,zeroDelayTimerMs:delay,timerRanDuringImport};
console.log(JSON.stringify(result,null,2));
fs.writeFileSync(path.join(output,'import-performance.json'),JSON.stringify(result,null,2)+'\n');
